// The supporting pages.
//
// WHY THIS FILE EXISTS
// The site was one page, and a single page can rank for a single cluster of
// searches. The SEO audit of 27.08.2026 measured the gap: the copy never
// contains "תוכנת רכש", "ניהול ספקים" or "התאמת חשבונית להזמנה", and never
// mentions the accounting systems an Israeli buyer would search alongside them.
// The home page argues the product well; it cannot also be six answers to six
// different questions.
//
// WHY NOT IN he.ts
// scripts/gates/g2-content-parity.mjs locks src/content/he.ts to build 3's
// wording leaf by leaf, so any addition there fails the build. Same reason
// src/content/extra.ts exists.
//
// WHERE THE CLAIMS COME FROM
// Every capability sentence below is traceable to a document in the product
// repository, and the `source` field on each page names them. Nothing here
// describes behaviour that is not written down somewhere else:
//
//   ../NIR-APP/PRODUCT.md               the three roles, the capability
//                                       contract, the journey, the principles
//   ../NIR-APP/brand/positioning.md     the category, the proof points, and the
//                                       explicit list of what InPlace refuses
//                                       to be
//   ../NIR-APP/brand/audience.md        the three archetypes and their words
//   ../NIR-APP/brand/context.md         the name, the alternatives, the values
//   src/content/he.ts                   the plan catalogue and the figures
//
// HOUSE RULES, same as he.ts: no em-dash in visible copy, the brand name is
// marked by emphasiseBrand rather than by hand, and no figure appears without a
// source beside it.

export type Section = {
  h2: string
  /** Runs before the list or the table, and introduces it. */
  paras?: string[]
  list?: { label: string; items: string[] }
  table?: { headers: [string, string]; rows: [string, string][] }
  /** Runs after the list or the table, and closes the section. */
  after?: string[]
  /**
   * Print the two founders here, between the paragraphs and the table.
   *
   * Set on exactly one section of one page. The names and the biography are in
   * src/content/people.ts rather than in the copy above, because the two
   * structured-data generators declare the same people and a second copy in
   * prose is a second copy that nothing compares.
   */
  people?: true
  /**
   * This `h2` is a question, and `paras` (with `after`) are its answer.
   *
   * WHY THE FLAG AND NOT A HEURISTIC
   * The SEO audit of 31.08.2026 found `FAQPage` on the home page and nowhere
   * else, while these pages were already written as questions with self-
   * contained answers under them: twenty-six of them, unmarked. An answer engine
   * lifts a question and its answer as a unit when it is told they are one, and
   * had to guess here.
   *
   * The obvious shortcut is to test whether the heading opens with מה / מי /
   * למה / מתי, and it is wrong. "קבלת סחורה מהטלפון" answers a question nobody
   * asked in the heading, and "עלות ההטמעה, לא עלות הרישיון" is an argument, not
   * a question. Both would pass a prefix test and neither is a question and
   * answer. So the marking is a decision per section, made once, in the same
   * file as the words it describes.
   *
   * Two rules hold it honest, and scripts/gates/g21-schema.mjs enforces the
   * first from the built page in both directions:
   *   - a section marked `ask` prints `data-faq-q`, and every printed question
   *     is declared in the graph, and every declared question is printed;
   *   - a section marked `ask` must carry `paras`, because a Question whose
   *     Answer has no text is a question the engine cannot lift.
   *
   * The two legal documents carry none. Their headings are numbered clauses,
   * and a clause is not an answer to a question the reader asked.
   */
  ask?: true
}

export type Page = {
  slug: string
  title: string
  description: string
  eyebrow: string
  /** What the page is called in a list of links, where 'comparison' twice says nothing. */
  nav: string
  h1: string
  lede: string
  sections: Section[]
  /**
   * One screen of the product, on the page that describes it.
   *
   * Added 28.08.2026. Until then these eight pages carried no picture at all:
   * `/invoice-matching/` explained the invoice check and did not show the
   * screen that performs it, while the screen itself sat on the home page under
   * an `alt` written for the home page's argument. That cost twice over — a
   * page with only text is picked less often by an answer engine, and an image
   * ranks on the context around it, and the strongest context these six shots
   * will ever have is the page that is about exactly them.
   *
   * The two legal documents carry none, and that is not an oversight: no screen
   * in the product depicts a terms of use, and a screenshot chosen to fill the
   * space would be decoration on the one page a reader is reading in order to
   * decide something.
   *
   * `alt` is written for this page and this screen. `cap` is the line under it,
   * and it says what the picture is doing in this argument.
   *
   * WHY THESE ARE NOT THE HOME PAGE'S SIX SCREENS
   * The first cut of this field reused them, and the owner's instruction of
   * 28.08.2026 was that it must not: a reader arriving from the home page would
   * meet the same picture twice, and image search would be offered one file
   * claiming to be two subjects. These are six OTHER screens of the same
   * product — suppliers, credits, alerts, price lists, supplier performance,
   * bank reconciliation — captured from the running application and listed in
   * scripts/build-doc-shots.mjs against the page each belongs to.
   *
   * `w` and `h` are the real pixel size of the file, per image rather than a
   * constant, because two of the six are cropped and are therefore not the
   * 2000x1333 the other four are. A width or height attribute that disagrees
   * with the file reserves the wrong amount of space and moves the page as the
   * picture lands, which is the layout shift these attributes exist to prevent.
   */
  image?: { src: string; w: number; h: number; alt: string; cap: string }
  related: string[]
  source: string
  /**
   * Set on the two legal documents.
   *
   * They are not marketing pages: they carry the exact text a user consents to
   * inside the product. A legal page therefore takes no call to action and no
   * further-reading rail — a document that argues for the product while the
   * reader is deciding whether to accept it is a different document.
   *
   * The text is copied from NIR-APP `src/pages/Legal.tsx`, word for word. If it
   * is edited there, this copy is stale until it moves with it. That is the
   * whole risk of a second copy, written down.
   *
   * The version string the product stamps on consent is deliberately NOT
   * printed here: the owner's note of 27.08.2026 is that a reader of a public
   * page has no use for it, and it read as machinery rather than as terms.
   */
  legal?: true
}

