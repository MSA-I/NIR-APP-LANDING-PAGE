/* Locale dictionaries (en.ts, fr.ts) are typed as `Dict`, so they must match
   `he` key for key and array length for array length. Only human-visible text
   may differ between locales: text literals widen to `string`, while the
   machine values the code branches on (`id`, `state`, and the `roles` lists)
   stay pinned to the exact values declared above. Without the widening, the
   `as const` below would pin every string to its Hebrew literal and no
   translation could ever satisfy `Dict`. */
type MachineKey = 'id' | 'state' | 'roles';

type Localized<T> = T extends string
  ? string
  : T extends readonly unknown[]
    ? { readonly [K in keyof T]: Localized<T[K]> }
    : T extends object
      ? {
          readonly [K in keyof T]: K extends MachineKey
            ? T[K] extends string | readonly string[]
              ? T[K]
              : Localized<T[K]>
            : Localized<T[K]>;
        }
      : T;

export type Dict = Localized<typeof he>;
